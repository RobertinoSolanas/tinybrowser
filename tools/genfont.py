lines.append("pub const ASCENT_ROWS: usize = 6;")
lines.append("pub const DESCENT_ROWS: usize = 1;")
lines.append("")
lines.append(f"/// ASCII {ASCII_START}..={ASCII_END} (`space` .. `~`), 95 glyphs.")
lines.append("pub const ASCII: [[u8; 7]; 95] = [")
for code in range(ASCII_START, ASCII_END + 1):
    ch = chr(code)
    rows = G[ch]
    lines.append(
        "    [%s], // %s %r" % (
            ", ".join(f"0b{r:05b}" for r in rows),
            hex(code),
            ch,
        )
    )
lines.append("];")
lines.append("")
extras = [(c, r) for c, r in G.items() if ord(c) > ASCII_END]
lines.append("/// Non-ASCII glyphs we care about (German umlauts, dashes, quotes, …).")
lines.append("pub const EXTRA: &[(char, [u8; 7])] = &[")
for c, rows in extras:
    lines.append(
        "    (%r, [%s])," % (c, ", ".join(f"0b{r:05b}" for r in rows))
    )
lines.append("];")
lines.append("")

with open("crates/tb-gfx/src/font_data.rs", "w") as f:
    f.write("\n".join(lines))
print("glyphs:", len(G), "ascii:", ASCII_END - ASCII_START + 1, "extras:", len(extras))
