G = {}

def glyph(ch, *rows):
    assert len(rows) == 7, f"{ch!r}: {len(rows)} rows"
    bits = []
    for r in rows:
        assert len(r) == 5, f"{ch!r} row {r!r} has {len(r)} cols"
        v = 0
        for c in r:
            v = (v << 1) | (1 if c == "#" else 0)
        bits.append(v)
    G[ch] = bits

